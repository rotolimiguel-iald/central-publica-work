"""Segundo aperto da frente (ainda 41.101 B > 40.960): três trocas editoriais na prosa do gerador, sem tocar número, URL, estatuto,
errata ou verbatim. Trocas contadas; backup de bytes; py_compile antes de substituir."""
import os, py_compile, time
from pathlib import Path

P = Path("C:/IALD/Artigo/the_boundary/tools/gerar_readme_frente.py")
TS = time.strftime("%Y%m%d_%H%M%S")
raw = P.read_bytes()
s = raw.decode("utf-8")
if "verbatim, is in `ESTADO_ATUAL.md` (linked above)" in s:
    raise SystemExit("já aplicado")


def troca(old, new, rot):
    global s
    n = s.count(old)
    assert n == 1, (rot, n, old[:80])
    s = s.replace(old, new)
    print("  ok  %-28s %+d" % (rot, len(new.encode("utf-8")) - len(old.encode("utf-8"))))


troca("             '`NOT_FALSIFIED_POWERED`; ln B(TGL/ΛCDM) = %.2f (not a σ). `NOT_FALSIFIED` is not accreditation; not blind to the data; the gate does not move. '\n"
      "             'The full paragraph, verbatim: [`ESTADO_ATUAL.md`](%s).\\n'\n"
      "             % (versao, data, _k, _l['z_disc_calibrado'], _l['p_disc_unilateral'], _l['z_disc_calibrado'], _l['z_delta_calibrado'],\n"
      "                _l['p_delta_bilateral'], _l['poder_previo'], _l['lnB_lcdm'], u_estado))\n",
      "             '`NOT_FALSIFIED_POWERED`; ln B(TGL/ΛCDM) = %.2f (not a σ); not blind to the data; the gate does not move. '\n"
      "             'The full paragraph, verbatim, is in `ESTADO_ATUAL.md` (linked above).\\n'\n"
      "             % (versao, data, _k, _l['z_disc_calibrado'], _l['p_disc_unilateral'], _l['z_disc_calibrado'], _l['z_delta_calibrado'],\n"
      "                _l['p_delta_bilateral'], _l['poder_previo'], _l['lnB_lcdm']))\n", "item do 4,44 (remissão)")
troca("*Generated by script (`tools/gerar_readme_frente.py`) from the seal on {hoje}; URLs from `TUNEL.json`/`PORTA.json`, numbers from the seal. NOT_FALSIFIED ≠ CONFIRMED.*",
      "*Generated by `tools/gerar_readme_frente.py` from the seal on {hoje} (URLs from `TUNEL.json`/`PORTA.json`). NOT_FALSIFIED ≠ CONFIRMED.*", "rodapé")

P.with_name(P.name + ".bak_" + TS).write_bytes(raw)
t = P.with_name(P.name + ".tmp")
t.write_bytes(s.encode("utf-8"))
py_compile.compile(str(t), doraise=True)
os.replace(t, P)
print("gerar_readme_frente.py: segundo aperto | %d -> %d bytes | backup .bak_%s" % (len(raw), P.stat().st_size, TS))
