import os, time
from pathlib import Path

P = Path(r"C:\IALD\Artigo\the_boundary\tools\gerar_readme_frente.py")
raw = P.read_bytes()
s = raw.decode("utf-8")
if "central-publica" in s:
    print("já aplicado"); raise SystemExit
crlf = b"\r\n" in raw
pares = [
    ("    F.append('\\n> **Beside (%s):** the Zenodo link above is a previous deposit; the current deposit is **%s** \\u2014 [%s](https://doi.org/%s), deposited %s%s.\\n' % (DEP_DATA, DEP_V, DEP_DOI, DEP_DOI, DEP_DATA, ', byte-identical to this seal' if DEP_V == versao else ', older than this seal'))\n",
     "    F.append('\\n> **Beside:** current Zenodo deposit: **%s** \\u2014 [%s](https://doi.org/%s).\\n' % (DEP_V, DEP_DOI, DEP_DOI))\n"
     "# 22/10/2026 (ordem do operador): a Central aberta, vinculada a este repositório\n"
     "F.append('\\n> **The Central, open (2026-10-22):** every code and result \\u2014 [central-publica](https://github.com/rotolimiguel-iald/central-publica) '\n"
     "         '(+ [work](https://github.com/rotolimiguel-iald/central-publica-work), [bancada](https://github.com/rotolimiguel-iald/central-publica-bancada)) '\n"
     "         '\\u00b7 [view-only](https://teoriadagravitacaoluminodinamica.com/central/) \\u00b7 [um.acom](https://teoriadagravitacaoluminodinamica.com/central/um.acom).\\n')\n"),
    ("*Generated by script (`tools/gerar_readme_frente.py`) from the sealed artifacts on {hoje}. Every URL comes from `TUNEL.json` / `PORTA.json`; every number from the seal. The gate does not move by this page. NOT_FALSIFIED ≠ CONFIRMED.*",
     "*Generated by script (`tools/gerar_readme_frente.py`) from the seal on {hoje}; URLs from `TUNEL.json`/`PORTA.json`, numbers from the seal. NOT_FALSIFIED ≠ CONFIRMED.*"),
]
for a, b in pares:
    if crlf:
        a, b = a.replace("\n", "\r\n"), b.replace("\n", "\r\n")
    assert s.count(a) == 1, (s.count(a), a[:90])
    s = s.replace(a, b)
compile(s, str(P), "exec")
P.with_name(P.name + ".bak_" + time.strftime("%Y%m%d_%H%M%S")).write_bytes(raw)
t = P.with_name(P.name + ".tmp_central")
